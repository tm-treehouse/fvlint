"""Generate tests/fixtures/scale_<n>.v: n independent bounded counters.

Used by the 'perf' regression cases to catch throughput regressions.
    python tests/regress/gen_scale.py 200
"""
import os
import sys

n = int(sys.argv[1]) if len(sys.argv) > 1 else 200
here = os.path.dirname(os.path.abspath(__file__))
path = os.path.join(here, "..", "fixtures", f"scale_{n}.v")
with open(path, "w") as f:
    f.write("// SPDX-FileCopyrightText: 2026 The fvlint Authors\n// SPDX-License-Identifier: ISC\n//\n")
    f.write(f"// Generated by tests/regress/gen_scale.py {n}: {n} independent bounded counters.\n\n")
    f.write(f"module scale_{n} (input clk, input rst, input [{n - 1}:0] en, output [{n - 1}:0] hit);\n")
    for i in range(n):
        lim = 100 + (i * 37) % 800
        f.write(f"  reg [9:0] c{i};\n  always @(posedge clk) if (rst) c{i} <= 10'd0; "
                f"else if (en[{i}]) c{i} <= (c{i} == 10'd{lim}) ? 10'd0 : c{i} + 10'd1;\n")
        f.write(f"  assign hit[{i}] = (c{i} == 10'd5);\n")
    f.write("endmodule\n")
print(path)
